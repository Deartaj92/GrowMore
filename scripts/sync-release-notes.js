const fs = require('fs');
const path = require('path');

// Read RELEASE_NOTES.md
const releaseNotesPath = path.join(__dirname, '..', 'RELEASE_NOTES.md');
const outputPath = path.join(__dirname, '..', 'src', 'utils', 'releaseNotes.ts');

try {
  const releaseNotesContent = fs.readFileSync(releaseNotesPath, 'utf8');
  
  // Preserve markdown format - just extract content after the first header
  let formattedNotes = '';
  
  // Remove any header text before the first section (like "What's New!" or "# What's New!")
  let content = releaseNotesContent.trim();
  
  // Find the first line that starts with # or *
  const lines = content.split('\n');
  let startIndex = 0;
  
  // Skip lines until we find a section header (# or *)
  for (let i = 0; i < lines.length; i++) {
    const line = lines[i].trim();
    if (line.startsWith('#') || line.startsWith('*')) {
      startIndex = i;
      break;
    }
  }
  
  if (startIndex > 0) {
    // Skip lines before the first section
    content = lines.slice(startIndex).join('\n');
  }
  
  // Preserve all markdown formatting (headers, bold, lists, etc.)
  formattedNotes = content.trimEnd();
  // Ensure it doesn't start with newlines
  formattedNotes = formattedNotes.replace(/^\n+/, '');
  
  // Escape backticks and template literals for TypeScript
  const escapedNotes = formattedNotes
    .replace(/\\/g, '\\\\')
    .replace(/`/g, '\\`')
    .replace(/\${/g, '\\${');
  
  // Generate TypeScript file
  const tsContent = `// Release notes content - auto-generated from RELEASE_NOTES.md
// Run: npm run sync-release-notes (or node scripts/sync-release-notes.js)
// DO NOT EDIT THIS FILE MANUALLY - it will be overwritten

export const getReleaseNotes = (): string => {
  return \`${escapedNotes}\`;
};
`;

  fs.writeFileSync(outputPath, tsContent, 'utf8');
  console.log('✅ Release notes synced successfully from RELEASE_NOTES.md');
  console.log('📝 Formatted notes:');
  console.log(formattedNotes);
} catch (error) {
  console.error('❌ Error syncing release notes:', error.message);
  process.exit(1);
}

